class BrandAssetManager:
    """Single entry point for icons, logos, and visual assets."""

    @staticmethod
    def icon_paths(name: str) -> str:
        return LUCIDE_ICONS.get(name, LUCIDE_ICONS["circle"])

    @staticmethod
    def has_icon(name: str) -> bool:
        return name in LUCIDE_ICONS

    @staticmethod
    def payment_logo_url(method: str) -> str:
        path = PAYMENT_LOGOS.get(method, "")
        if path and finders.find(path):
            return static(path)
        return static("images/payments/bank.svg")

    @staticmethod
    def payment_methods():
        from apps.payments.constants import PAYMENT_METHOD_META

        methods = {}
        for key, meta in PAYMENT_METHOD_META.items():
            methods[key] = {
                **meta,
                "logo_url": BrandAssetManager.payment_logo_url(key),
            }
        return methods

    @staticmethod
    def status_badge(label: str) -> dict:
        key = label.upper()
        return STATUS_BADGES.get(key, {"icon": "circle", "color": "slate", "label": label})

    @staticmethod
    def lesson_icon(lesson_type: str) -> str:
        return LESSON_TYPE_ICONS.get(lesson_type, "book-open")

    @staticmethod
    def empty_state(name: str) -> str:
        path = EMPTY_STATES.get(name, "")
        return static(path) if path and finders.find(path) else ""

    @staticmethod
    def site_stat_icon(icon_key: str) -> str:
        """Map seed/CMS icon keys (formerly emojis) to Lucide names."""
        mapping = {
            "students": "users",
            "courses": "book-open",
            "graduates": "graduation-cap",
            "certificates": "award",
            "instructors": "user-check",
            "👨‍🎓": "users",
            "📚": "book-open",
            "🎓": "graduation-cap",
            "🏆": "award",
            "👩‍🏫": "user-check",
        }
        return mapping.get(icon_key, icon_key if icon_key in LUCIDE_ICONS else "circle")
